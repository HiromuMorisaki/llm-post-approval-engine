_PROMPTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "prompts")


def load_persona() -> str:
    """ペルソナ（事実台帳・口調・禁止事項）を読み込む。

    実運用の prompts/persona.md は個人情報を含むため .gitignore 済み。
    無ければ公開用のサンプル prompts/persona.example.md を使う。
    """
    for name in ("persona.md", "persona.example.md"):
        path = os.path.join(_PROMPTS_DIR, name)
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                return f.read()
    raise FileNotFoundError("prompts/persona.md (or persona.example.md) not found.")

