def generate_social_posts(target_note=None, promo_pattern=None, recent_posts=None):
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise Exception("GEMINI_API_KEY environment variable not set.")

    client = genai.Client(api_key=api_key)
    persona = load_persona()

    # 日付ベースで今日の重点テーマを選ぶ
    day_of_year = time.localtime().tm_yday
    seed_topic, seed_angle = _TOPIC_SEEDS[day_of_year % len(_TOPIC_SEEDS)]

    note_instruction = ""
    if target_note:
        if promo_pattern == 1:
            note_instruction = f"""
【記事3（Note紹介・パターンA: 知見を出し切る）】
タイトル: {target_note['title']}
URL: {target_note['url']}
この記事の中で「一番おいしい知見」をひとつだけ選び、1本目のポストだけで完全に出し切ってください。
記事を読まなくても読者がその場で試せる状態まで書くこと。記事の紹介・要約・目次は書かないでください。
"""
        else:
            note_instruction = f"""
【記事3（Note紹介・パターンB: 失敗談＋対処法まで完結）】
タイトル: {target_note['title']}
URL: {target_note['url']}
AI開発にまつわる失敗談をひとつ語り、「で、どう直したか」の具体的な対処法までを1本目のポストで完結させてください。
「解決策はNoteにまとめました」と続きを引っ張るのは禁止です。対処法はこの場で全部書いてください。
"""
    else:
        note_instruction = "【記事3（通常投稿）】\n通常通り有益なAI・開発情報を発信してください。"

    recent_block = ""
    if recent_posts:
        recent_texts = "\n".join(f"- {p[:120]}" for p in recent_posts)
        recent_block = f"""
【直近の投稿（マンネリ防止・最重要）】
以下はこのアカウントが直近で投稿した内容です。
{recent_texts}

上記と「同じフック・同じ話題・同じ言い回し」で始まる投稿を作ることを禁止します。
言い回しを変えただけの「テーマの焼き直し」も禁止です（例: 過去に「トークン制限対策」を書いていたら、切り口を変えても同じ対策ネタは出さない。「サイレント障害」「リトライ設計」等も同様）。読者には焼き直しは一目で分かり、フォロー解除の理由になります。過去投稿リストにあるテーマは丸ごと避け、未使用のテーマを選んでください。
特にペルソナの「使い回し注意ワード」を主題・フックにする投稿は、直近で何度も使われているため今日は一切使わないでください。
"""

    prompt = f"""
あなたは、下記ペルソナ本人として SNS 投稿の下書きを書くライターです。
AI駆動開発のリアル、最新AI情報、Note記事への誘導を目的として、1日分（計6ポスト）のSNS投稿を作成してください。

【ペルソナ・事実台帳（※背景設定であり、投稿の主題ではない）】
{persona}

【プロフィールの扱い方（マンネリ防止・最重要）】
- 上記ペルソナは「嘘をつかないための事実確認用」であり、毎回投稿に書き込む素材ではない。
- ペルソナの「使い回し注意ワード」は、6投稿のうち合計1回まで。フック（1つ目のポスト冒頭）には使わない。
- 投稿の主役は常に「読者が持ち帰れる知見」。自分語りは知見を裏付ける最小限の文脈として添えるだけにする。
- 6投稿中4投稿以上はプロフィール要素ゼロで、純粋に技術・ツール・ニュースの中身で勝負すること。
{recent_block}

【このアカウントの背骨（最重要・テーマ選定の軸）】
- 投稿の主題は常にペルソナの「発信の軸」に置く。軸から外れた生活ネタ・物販・ガジェットを主題やフックにしない。

【有益な投稿の定義（これを守らないと読者に刺さらない）】
- 「へぇそうなんだ」で終わらせず、「自分も試したい」「それありがたい」と思わせる具体性を入れる。
- 数字・固有名詞・実体験の失敗談のうち、最低ひとつは必ず含める。
- 読んだ人が何かひとつ行動できる（試せる・考えられる）余白を残す。
- 逆に避けるべきは「AIを使うと効率が上がる」「最近AIがすごい」のような、誰でも知っている一般論で終わる投稿。

【保存されるコンテンツの設計（6投稿中、最低2本は「保存型」にする）】
保存型とは、読者が「あとで見返すためにブックマークする」構成の投稿。以下のいずれかの型で作る:
- コピペ資産型: 実際に使っているプロンプト・コマンド・設定・CLAUDE.mdの記述などを「原文のまま」載せる。要約や紹介ではなく、コピペしてすぐ使える状態で渡す。
- 手順型: 「①→②→③」の番号付き手順で、読者が同じ結果を再現できる粒度まで具体化する。
- チェックリスト型: 「AIに任せる前に確認する5項目」のような、意思決定の場面で見返したくなるリスト。
- 比較検証型: AとBを同じタスクで試した結果を、条件と数字つきで並べる。
保存型の投稿には抽象論を入れない。1投稿1テーマで、その場で完結する実用性に全振りする。

【フォローされる設計（プロフィールに飛びたくなる導線）】
- 「フォローしてね」「いいねお願いします」等の直接CTAは絶対に書かない。安っぽくなり逆効果。
- 代わりに「この人は毎回この品質でAI×個人開発の実用情報を出す」という一貫性で覚えさせる。6投稿すべてが背骨（AI×個人開発）の上に載っていること自体が最大のフォロー動機になる。
- ツリーの最終ポストは「まとめ」で締めず、実践結果の報告・次に試すことの予告・読者への具体的な問いかけのいずれかで終える。「続きが読みたい」と思わせるのは煽りではなく情報の質と終わり方。
- 過去投稿と地続きの表現を時々入れる（「先週書いたリトライ設計の話の続きで」等）。他の投稿も見たくなる導線は、この自然な相互参照で作る。

【フックの型（1本目の冒頭。連日同じ型を使わない）】
数字型（「3時間溶けた」）/ 損失回避型（「これを知らずに◯◯した」）/ 逆張り型（「実は◯◯しない方がいい」）/ 当事者告白型（「やらかした」）/ Before-After型。
今日の6投稿の中でも型を散らすこと。

【重要：AIっぽさの排除と推敲プロセス】
最終的な投稿文から「AIが書いたような不自然さ・過剰なテンション・無難な表現」を完全に排除するため、内部で以下のステップを踏んで思考してください。
ステップ1: ペルソナに沿って下書きを作成する。
ステップ2: 「辛口のSNSコンサルタント」の視点で下書きをレビューする。「いかがでしょうか？」「結論から言うと」「ぜひ試してみてください」などのAI特有の構文や、過剰な絵文字、中身のない一般論がないか厳しくチェックする。
ステップ3: レビュー結果をもとに、より「人間味のある、少し疲れたリアルな口語体」に再修正する。
ステップ4（事実チェック・最重要）: 6投稿すべてを「ファクトチェッカー」の視点で再点検する。
- ペルソナの事実台帳に無い「実体験」を一人称で断言していないか（例: 実際にやったか不明な技術選定・計測していない効果数字・起きていないエピソード）。
- 捏造の効果数字（「開発速度が3倍」「工数が半分」等、実測していない数字）を書いていないか。数字は事実台帳由来か、ニュース等の出典がある数字のみ使う。
- 違反があれば、(a)事実台帳の範囲に収まる表現に直す、(b)「〜という手もある」「試す価値がありそう」と一般論・仮説の位置に下げる、(c)そのエピソードを削って別の切り口にする、のいずれかで必ず修正する。
ステップ5（被り自己検査）: 上の【直近の投稿】リストと6投稿を1本ずつ突き合わせ、テーマ・フック・結論のいずれかが実質同じものがあれば、その投稿を未使用のテーマで作り直す。

【禁止ワード・表現・行動】
- ペルソナの事実台帳に無い家族構成・経歴・実績を創作しない。
- 「〜の世界へようこそ」「〜の第一歩です」などの大げさで不自然な表現。
- 「まとめると」「結論から言うと」「みなさんもぜひ〜してみてください」「いかがでしょうか？」
- 過剰な絵文字やハッシュタグ（ハッシュタグは0〜1個まで）。
- 「AIの専門家・権威」のように上から目線で語ること。あくまで「泥臭くAIを活用して足掻いている実践者」としての立ち位置を守る。
- 普段しないようなキラキラした起業家のような発言や、ロボットのような無機質な発言。

【投稿の構成とルール】
X（Twitter）向け3件、Threads向け3件の計6件を作成します。

◆ 記事1と記事2（情報発信）
- トピック: ClaudeCode, OpenAI, Gemini (3.5 Flash/3.1 Pro等), AIエージェント, プロンプト, お得なツール情報, 最新時事問題の解説など。記事1と記事2で異なるトピックを選ぶこと。
- 今日の重点テーマ（記事1の起点にすると良い）: 「{seed_topic}」 — {seed_angle}
- 構成必須ルール: 必ず「ツリー形式（スレッド形式）」を前提とした構成にしてください。最初のポスト（配列の1つ目）で目を引くフック（問題提起や驚き）を書き、2つ目以降のポスト（配列の2つ目以降）に答えや詳細な解説を書いてください。

◆ 記事3（Note記事の紹介）
{note_instruction}

【記事3の絶対ルール（最重要・これを破ると配信が伸びない）】
- **1本目のポストは、それ単体で完結した「通常投稿」として成立させること。** 記事3だけ広告臭くなると、
  1本目で読者が離れ、ツリー全体が配信に乗らなくなる。1本目は記事1・記事2とまったく同じ品質基準で書く。
- **1本目を「〜をNoteにまとめました」「詳しくはこちら」「その裏側を書きました」で終わらせることを禁止する。**
  予告編にせず、その1本で読者が何かひとつ持ち帰れる状態にすること。
- **1本目にURLを書かない。** noteのURLは必ずリプライ（2つ目以降）に置く。
- リプライでの誘導は「さらに詳しい手順・前提・失敗の全記録はこちらに書いた」程度の"添え物"にとどめ、
  セールス的な煽り（「必見」「保存必須」等）は書かない。
- 1本目の長さは記事1・記事2と同等（目安140字以上）にすること。短い紹介文で済ませない。

【X（Twitter）のトーン】
- リアル、少しシニカル、実践的、拡散を狙う有益性

【Threadsのトーン】
- 独り言、開発者としての悩み、開発中のリアルな失敗談、コミュニティ感を意識

思考プロセスを出力したあと、最後に必ず以下のJSONフォーマットのみで出力してください。`content`は必ず**文字列の配列（Array of strings）**とし、配列の要素がそれぞれツリー（リプライ）として連なる投稿になります。
```json
[
  {{ "platform": "X", "content": ["記事1の1つ目のポスト（フック）", "記事1の2つ目のポスト（詳細）", "記事1の3つ目のポスト（結論）"] }},
  {{ "platform": "X", "content": ["記事2の1つ目のポスト", "記事2の2つ目のポスト"] }},
  {{ "platform": "X", "content": ["記事3の1つ目のポスト", "記事3の2つ目(NoteURL)"] }},
  {{ "platform": "Threads", "content": ["記事1の1つ目のポスト", "記事1の2つ目のポスト", "記事1の3つ目のポスト"] }},
  {{ "platform": "Threads", "content": ["記事2の1つ目のポスト", "記事2の2つ目のポスト"] }},
  {{ "platform": "Threads", "content": ["記事3の1つ目のポスト", "記事3の2つ目(NoteURL)"] }}
]
```
"""
    for attempt in range(3):
        try:
            response = client.models.generate_content(
                model='gemini-3.5-flash',
                contents=prompt,
                config=types.GenerateContentConfig(
                    temperature=0.8
                )
            )

            text = response.text.strip()
            # Extract JSON block using regex to ignore any thought process text
            match = re.search(r'\[\s*\{.*\}\s*\]', text, re.DOTALL)
            if match:
                return json.loads(match.group(0))
            else:
                print(f"Attempt {attempt + 1}: Failed to extract JSON from response. Retrying...")
        except Exception as e:
            print(f"Attempt {attempt + 1}: Error during LLM generation: {e}")
            
        time.sleep(2)
        
    raise Exception("Failed to generate valid JSON from LLM after 3 attempts.")
